"""Run against npm run dev with Playwright installed. Optional BASELINE_URL for screenshots."""
import os
from pathlib import Path
from playwright.sync_api import expect, sync_playwright

target = os.getenv('VECTOR_URL', 'http://localhost:5173/#hdl-vectors')
baseline = os.getenv('BASELINE_URL')
screens = Path(os.getenv('VECTOR_SCREENSHOTS', '.sites-runtime/vector-review'))
screens.mkdir(parents=True, exist_ok=True)
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(executable_path=os.getenv('CHROMIUM_PATH'))
    for width in (320, 390, 768, 820, 1024, 1280, 1440):
        page = browser.new_page(viewport={'width': width, 'height': 1000}, has_touch=width <= 768)
        if baseline:
            page.goto(baseline)
            page.locator('#study-concept').wait_for()
            page.screenshot(path=screens / f'before-{width}.png')
        page.goto(target)
        expect(page.locator('#vector-current h2')).to_have_text('1. 认识向量')
        expect(page.locator('#vector-progress')).to_contain_text('0 / 6')
        page.screenshot(path=screens / f'after-{width}.png')
        check = page.locator('.vector-exercise button', has_text='检查')
        page.locator('[data-bit="5"]').press('Enter')
        check.click()
        expect(page.locator('#vector-feedback')).to_contain_text('选对了')
        page.locator('#vector-next').click()
        page.locator('[data-bit="3"]').click()
        expect(page.locator('#vector-expression')).to_have_text('bus[3]')
        page.locator('#vector-answer').fill('0')
        check.click()
        page.locator('#vector-input').fill('11111111')
        expect(page.locator('[data-step="1"]')).to_contain_text('需要复习')
        page.locator('#vector-answer').fill('1')
        check.click()
        expect(page.locator('#vector-feedback')).to_contain_text('答对了')
        page.locator('#vector-next').click()
        page.locator('#vector-hi').select_option('5')
        page.locator('#vector-lo').select_option('2')
        expect(page.locator('[data-bit][aria-pressed="true"]')).to_have_count(4)
        page.locator('#vector-answer').fill('1111')
        check.click()
        page.locator('#vector-next').click()
        page.locator('#vector-swap').click()
        expect(page.locator('#vector-result')).to_contain_text('1111_1111')
        page.locator('#vector-input').fill('11110000')
        expect(page.locator('#vector-result')).to_contain_text('0000_1111')
        check.click()
        page.locator('[data-step="1"]').click()
        page.locator('#vector-answer').fill('0')
        check.click()
        page.locator('[data-step="2"]').click()
        page.locator('#vector-answer').fill('1100')
        check.click()
        page.locator('[data-step="4"]').click()
        page.locator('#vector-count').select_option('6')
        expect(page.locator('#vector-result')).to_contain_text('111111')
        page.locator('#vector-answer').fill('6')
        check.click()
        page.locator('#vector-next').click()
        page.locator('[data-line="2"]').click()
        expect(page.locator('#vector-module-result')).to_contain_text('0000_1111')
        page.locator('#hdl-draft').fill("module swap8(input wire [7:0] bus, output wire [7:0] result); assign result = {bus[3:0],bus[7:4]}; endmodule")
        page.locator('#vector-change').fill('2')
        page.locator('#vector-fill').fill('bus[4:3]')
        page.locator('#vector-bridge button').click()
        page.locator('#vector-self').click()
        expect(page.locator('#vector-progress')).to_contain_text('6 / 6')
        page.reload()
        expect(page.locator('#vector-completion')).to_contain_text('未运行')
        assert page.locator('#hdl-draft').input_value().startswith('module swap8')
        assert page.evaluate('document.documentElement.scrollWidth === document.documentElement.clientWidth')
        print(f'PASS {width}px vector lesson interaction and reload')
        page.close()
